# Discovery alternatives generated by the pinned MCP SDK for the official issuer.
_PUBLIC_METADATA_URLS = frozenset(
    {
        AS_METADATA_URL,
        RESOURCE_METADATA_URL,
        "https://agent.robinhood.com/.well-known/oauth-protected-resource",
        "https://agent.robinhood.com/.well-known/oauth-authorization-server/mcp/trading",
        "https://agent.robinhood.com/mcp/trading/.well-known/oauth-authorization-server",
        "https://agent.robinhood.com/.well-known/openid-configuration/mcp/trading",
        "https://agent.robinhood.com/mcp/trading/.well-known/openid-configuration",
    }
)


def _guard_request(request: httpx.Request) -> None:
    url = str(request.url)
    if url not in _PUBLIC_METADATA_URLS | {
        TOKEN_ENDPOINT,
        REGISTRATION_ENDPOINT,
        OFFICIAL_MCP_ENDPOINT,
    }:
        raise RuntimeError("official OAuth request target denied")
    if "Authorization" in request.headers and (
        url != OFFICIAL_MCP_ENDPOINT or not request.headers["Authorization"].startswith("Bearer ")
    ):
        raise RuntimeError("official OAuth credential target denied")
    content_type = request.headers.get("content-type", "").split(";", 1)[0].strip().lower()
    if content_type == "application/x-www-form-urlencoded":
        fields = parse_qs(
            request.content.decode("ascii"), strict_parsing=True, keep_blank_values=True
        )
        credential_fields = {
            "grant_type",
            "refresh_token",
            "code",
            "code_verifier",
            "client_secret",
            "access_token",
        }
        if url != TOKEN_ENDPOINT and credential_fields.intersection(fields):
            raise RuntimeError("official OAuth grant body target denied")
        if url == TOKEN_ENDPOINT and (
            fields.get("grant_type") not in (["authorization_code"], ["refresh_token"])
            or "client_secret" in fields
        ):
            raise RuntimeError("official OAuth grant contract denied")
    elif url == TOKEN_ENDPOINT:
        raise RuntimeError("official OAuth grant encoding denied")
    if url in _PUBLIC_METADATA_URLS and request.method != "GET":
        raise RuntimeError("official OAuth metadata method denied")
    if url in {TOKEN_ENDPOINT, REGISTRATION_ENDPOINT} and request.method != "POST":
        raise RuntimeError("official OAuth endpoint method denied")


class PinnedOAuthTransport(httpx.AsyncBaseTransport):
    """Validate actual sends, including HTTPX-internal redirects; sanitize failures."""

    def __init__(
        self, inner: httpx.AsyncBaseTransport, *, operation_timeout_seconds: float = 30.0
    ) -> None:
        if not 0 < operation_timeout_seconds <= 30:
            raise ValueError("official OAuth operation timeout invalid")
        self._inner = inner
        self._operation_timeout = operation_timeout_seconds

    async def handle_async_request(self, request: httpx.Request) -> httpx.Response:
        _guard_request(request)
        response: httpx.Response | None = None
        auxiliary = str(request.url) in _PUBLIC_METADATA_URLS | {
            TOKEN_ENDPOINT,
            REGISTRATION_ENDPOINT,
        }
        try:
            if not auxiliary:
                response = await self._inner.handle_async_request(request)
                if 300 <= response.status_code < 400:
                    await response.aclose()
                    raise RuntimeError("official OAuth redirects disabled")
                return response
            async with asyncio.timeout(self._operation_timeout):
                response = await self._inner.handle_async_request(request)
                if 300 <= response.status_code < 400:
                    raise RuntimeError("official OAuth redirects disabled")
                body = bytearray()
                async for chunk in response.aiter_bytes():
                    if len(body) + len(chunk) > 131072:
                        raise RuntimeError("official OAuth response too large")
                    body.extend(chunk)
                return httpx.Response(
                    response.status_code,
                    headers={
                        k: v
                        for k, v in response.headers.items()
                        if k.lower() not in {"content-encoding", "content-length"}
                    },
                    content=bytes(body),
                    request=request,
                )
        except Exception:
            raise RuntimeError("official OAuth transport unavailable") from None
        finally:
            if auxiliary and response is not None:
                with suppress(Exception):
                    await asyncio.wait_for(response.aclose(), timeout=1.0)

    async def aclose(self) -> None:
        await self._inner.aclose()


class LifecycleOAuthClientProvider(PinnedScopeOAuthClientProvider):
    """Restore actual expiry; persist pending before a single refresh POST.

    Construct with PinnedOAuthTransport. Token lifetime is observed protocol metadata,
    not a guarantee that the provider will accept the credential until that instant.
    """

    def __init__(
        self, *args: Any, clock: Callable[[], datetime] = lambda: datetime.now(UTC), **kwargs: Any
    ) -> None:
        super().__init__(*args, **kwargs)
        if not isinstance(self.context.storage, EncryptedFileTokenStorage):
            raise TypeError("official OAuth requires encrypted lifecycle storage")
        redirects = self.context.client_metadata.redirect_uris
        if not redirects or len(redirects) != 1:
            raise ValueError("official OAuth redirect identity required")
        self._redirect_uri = str(redirects[0])
        self._storage = self.context.storage
        self._clock = clock
        self._monotonic: Callable[[], float] = time.monotonic
        self._anchor_wall: datetime | None = None
        self._anchor_mono: float | None = None
        self._last_wall: datetime | None = None
        self._last_mono: float | None = None
        self._record: OAuthLifecycle | None = None
        self._token_request_started: datetime | None = None
        self._before_refresh: OAuthToken | None = None
        self._poisoned = False
        self._resource_pending = False
        self._resource_validated = False
        self.refreshes_completed = 0

    def _now(self) -> datetime:
        wall = require_utc(self._clock())
        mono = self._monotonic()
        if (self._last_wall is not None and wall < self._last_wall) or (
            self._last_mono is not None and mono < self._last_mono
        ):
            raise RuntimeError("official OAuth clock requires review")
        if self._anchor_wall is None or self._anchor_mono is None:
            self._anchor_wall, self._anchor_mono = wall, mono
        now = max(wall, self._anchor_wall + timedelta(seconds=mono - self._anchor_mono))
        if self._record is not None and now < self._record.last_observed_at:
            raise RuntimeError("official OAuth clock requires review")
        self._last_wall, self._last_mono = wall, mono
        return now

    async def _checkpoint(self) -> None:
        if self._record is not None:
            if self._record.state != "active" or self.context.current_tokens is None:
                raise RuntimeError("official OAuth state requires owner review")
            self._record = self._record.observe(self._now())
            persisted = (
                self._unusable_record("resource_validation_pending")
                if self._resource_pending
                else self._record
            )
            await self._storage.set_tokens_with_lifecycle(self.context.current_tokens, persisted)

    def _unusable_record(self, state: str) -> OAuthLifecycle:
        if self._record is None:
            raise RuntimeError("official OAuth lifecycle unavailable")
        return replace(
            self._record,
            state=state,
            expires_in=None,
            expires_at=None,
            response_received_at=None,
        )

    async def _deny_resource_generation(self) -> None:
        tokens = self.context.current_tokens
        if tokens is None:
            raise RuntimeError("official OAuth token unavailable")
        denied = self._unusable_record("reauthorization_required").observe(self._now())
        await self._storage.set_tokens_with_lifecycle(tokens, denied)
        self._record = denied
        raise RuntimeError("official OAuth owner sign-in required")

    def _metadata(self) -> tuple[dict[str, Any], dict[str, Any]]:
        if self.context.oauth_metadata is None or self.context.protected_resource_metadata is None:
            raise RuntimeError("official OAuth metadata unavailable")
        authorization = self.context.oauth_metadata.model_dump(mode="json", exclude_none=True)
        protected = self.context.protected_resource_metadata.model_dump(
            mode="json", exclude_none=True
        )
        validate_metadata(authorization, protected)
        return authorization, protected

    async def _initialize(self) -> None:
        try:
            await super()._initialize()
            self._record = await self._storage.get_lifecycle()
            if self._record is not None:
                if self._record.state != "active" or self.context.client_info is None:
                    raise RuntimeError("official OAuth owner recovery required")
                self._record.validate_client(self.context.client_info, self._redirect_uri)
                self._record = self._record.observe(self._now())
                self.context.oauth_metadata = OAuthMetadata.model_validate_json(
                    self._record.authorization_json
                )
                self.context.protected_resource_metadata = (
                    ProtectedResourceMetadata.model_validate_json(self._record.protected_json)
                )
                self.context.auth_server_url = OFFICIAL_MCP_ENDPOINT
                self.context.token_expiry_time = (
                    self._record.expires_at.timestamp() if self._record.expires_at else None
                )
                if self.context.current_tokens is None:
                    raise RuntimeError("official OAuth token unavailable")
                await self._storage.set_tokens_with_lifecycle(
                    self.context.current_tokens, self._record
                )
        except Exception:
            self._poisoned = True
            self.context.clear_tokens()
            raise RuntimeError("official OAuth state requires owner review") from None

    def _require_public_client(self) -> None:
        client = self.context.client_info
        if client is None or not client.client_id:
            raise RuntimeError("official OAuth client unavailable")
        validate_public_client(client, client_id=client.client_id, redirect_uri=self._redirect_uri)
        if self._record is not None:
            self._record.validate_client(client, self._redirect_uri)

    async def _perform_authorization_code_grant(self) -> tuple[str, str]:
        self._metadata()
        self._require_public_client()
        return await super()._perform_authorization_code_grant()

    async def _refresh_token(self) -> httpx.Request:
        authorization, protected = self._metadata()
        tokens, client = self.context.current_tokens, self.context.client_info
        if (
            tokens is None
            or not tokens.refresh_token
            or client is None
            or not client.client_id
            or self._record is None
            or self._record.state != "active"
        ):
            raise RuntimeError("official OAuth refresh unavailable")
        self._require_public_client()
        pending = OAuthLifecycle.pending(
            client_id=client.client_id,
            authorization=authorization,
            protected=protected,
            at=self._now(),
            flow="automatic_refresh",
        )
        pending.validate_client(client, self._redirect_uri)
        await self._storage.set_tokens_with_lifecycle(tokens, pending)
        self._record = pending
        self._before_refresh = tokens
        self._token_request_started = pending.request_started_at
        return await super()._refresh_token()

    async def prepare_explicit_refresh(
        self, authorization: dict[str, Any], protected: dict[str, Any]
    ) -> httpx.Request:
        """One-shot migration of a legacy grant, never invented old-token expiry."""
        if not self._initialized:
            await self._initialize()
        validate_metadata(authorization, protected)
        client, tokens = self.context.client_info, self.context.current_tokens
        if (
            client is None
            or not client.client_id
            or tokens is None
            or not tokens.refresh_token
            or (self._record is not None and self._record.state != "active")
        ):
            raise RuntimeError("official OAuth refresh unavailable")
        self._require_public_client()
        pending = OAuthLifecycle.pending(
            client_id=client.client_id,
            authorization=authorization,
            protected=protected,
            at=self._now(),
            flow="explicit_refresh",
        )
        pending.validate_client(client, self._redirect_uri)
        self.context.oauth_metadata = OAuthMetadata.model_validate(authorization)
        self.context.protected_resource_metadata = ProtectedResourceMetadata.model_validate(
            protected
        )
        self.context.auth_server_url = OFFICIAL_MCP_ENDPOINT
        self._before_refresh = tokens
        self._record = pending
        self._token_request_started = pending.request_started_at
        await self._storage.set_tokens_with_lifecycle(tokens, pending)
        return await super()._refresh_token()

    async def _commit_response(self, response: httpx.Response, *, refreshing: bool) -> None:
        if str(response.request.url) != TOKEN_ENDPOINT:
            raise RuntimeError("official OAuth response target invalid")
        if response.status_code != 200:
            if refreshing and self._record is not None and self._before_refresh is not None:
                try:
                    error = response.json().get("error")
                except Exception:
                    error = None
                if error in {"invalid_grant", "invalid_client"}:
                    denied = replace(self._record, state="reauthorization_required")
                    await self._storage.set_tokens_with_lifecycle(self._before_refresh, denied)
                    self._record = denied
            raise RuntimeError("official OAuth renewal denied")
        if len(response.content) > 131072:
            raise RuntimeError("official OAuth response too large")
        raw = response.json()
        if (
            type(raw) is not dict
            or type(raw.get("access_token")) is not str
            or not 1 <= len(raw["access_token"]) <= 16384
            or type(raw.get("token_type")) is not str
            or raw["token_type"].lower() != "bearer"
            or raw.get("scope") not in {None, "internal"}
        ):
            raise RuntimeError("official OAuth token response invalid")
        if "refresh_token" in raw:
            if type(raw["refresh_token"]) is not str or not 1 <= len(raw["refresh_token"]) <= 16384:
                raise RuntimeError("official OAuth refresh credential invalid")
        elif refreshing and self._before_refresh is not None:
            # RFC6749 section6: omission retains the same client's old refresh credential.
            raw["refresh_token"] = self._before_refresh.refresh_token
        authorization, protected = self._metadata()
        client = self.context.client_info
        if client is None or not client.client_id or self._token_request_started is None:
            raise RuntimeError("official OAuth issuance provenance unavailable")
        pending = (
            self._record
            if refreshing
            else OAuthLifecycle.pending(
                client_id=client.client_id,
                authorization=authorization,
                protected=protected,
                at=self._token_request_started,
                flow="authorization_code",
            )
        )
        if pending is None or pending.state != "refresh_pending":
            raise RuntimeError("official OAuth issuance state invalid")
        active = pending.activate(received_at=self._now(), expires_in=raw.get("expires_in"))
        active.validate_client(client, self._redirect_uri)
        tokens = OAuthToken.model_validate(raw)
        if refreshing:
            # Acceptance belongs to this new generation, never an earlier one.
            self._resource_validated = False
            self._resource_pending = active.flow == "automatic_refresh"
        # Automatic renewal cannot become restart-reusable before its first
        # acknowledged resource response. Explicit renewal is a separate owner
        # token-endpoint-only migration and does not claim resource validation.
        persisted = (
            replace(
                active,
                state="resource_validation_pending",
                expires_in=None,
                expires_at=None,
                response_received_at=None,
            )
            if self._resource_pending
            else active
        )
        await self._storage.set_tokens_with_lifecycle(tokens, persisted)
        # Context becomes usable only after the complete token generation is committed.
        self._record = active
        self.context.current_tokens = tokens
        self.context.token_expiry_time = (
            active.expires_at.timestamp() if active.expires_at else None
        )
        if refreshing:
            self.refreshes_completed += 1
        self._before_refresh = None

    async def _handle_token_response(self, response: httpx.Response) -> None:
        await self._safe_commit_response(response, refreshing=False)

    async def _handle_refresh_response(self, response: httpx.Response) -> bool:
        await self._safe_commit_response(response, refreshing=True)
        return True

    async def _safe_commit_response(self, response: httpx.Response, *, refreshing: bool) -> None:
        try:
            await self._commit_response(response, refreshing=refreshing)
        except BaseException as exc:
            self._poisoned = True
            self.context.clear_tokens()
            if not isinstance(exc, Exception):
                raise
            raise RuntimeError("official OAuth response rejected safely") from None

    async def _headless_flow(
        self, request: httpx.Request
    ) -> AsyncGenerator[httpx.Request, httpx.Response]:
        async with self.context.lock:
            if not self._initialized:
                await self._initialize()
            if (
                self._poisoned
                or (self._record is not None and self._record.state != "active")
                or self.context.current_tokens is None
                or self.context.client_info is None
            ):
                raise RuntimeError("official OAuth authentication unavailable")
            refreshed = False
            if (
                self._record is not None
                and self._record.expires_at is not None
                and self._now() >= self._record.expires_at
            ):
                response = yield await self._refresh_token()
                await self._handle_refresh_response(response)
                refreshed = True
            await self._checkpoint()
            self._add_auth_header(request)
            response = yield request
            await self._checkpoint()
            self._require_safe_challenge(response)
            if response.status_code == 401:
                if refreshed or self._record is None:
                    raise RuntimeError("official OAuth owner sign-in required")
                response = yield await self._refresh_token()
                await self._handle_refresh_response(response)
                await self._checkpoint()
                self._add_auth_header(request)
                response = yield request
                await self._checkpoint()
                self._require_safe_challenge(response)
                if response.status_code == 401:
                    raise RuntimeError("official OAuth authorization rejected")

    async def async_auth_flow(
        self, request: httpx.Request
    ) -> AsyncGenerator[httpx.Request, httpx.Response]:
        if str(request.url) != OFFICIAL_MCP_ENDPOINT or self._poisoned:
            raise RuntimeError("official OAuth request denied")
        delegated = (
            super().async_auth_flow(request)
            if self.context.callback_handler is not None
            else self._headless_flow(request)
        )
        failed = True
        try:
            outgoing = await anext(delegated)
            while True:
                self._require_pinned_scope_contract()
                _guard_request(outgoing)
                if str(outgoing.url) == OFFICIAL_MCP_ENDPOINT and self._record is not None:
                    if self._record.expires_at is None or self._now() >= self._record.expires_at:
                        raise RuntimeError("official OAuth expired generation denied")
                    # Persist a non-reusable state before the first resource send
                    # after rotation. Process death or a failed denial write must
                    # not let a fresh daemon repeat a rejected refresh generation.
                    if self.refreshes_completed and not self._resource_validated:
                        self._resource_pending = True
                    await self._checkpoint()
                if str(outgoing.url) == REGISTRATION_ENDPOINT:
                    self._metadata()
                if str(outgoing.url) == TOKEN_ENDPOINT:
                    self._metadata()
                    self._require_public_client()
                    parameters = parse_qs(outgoing.content.decode("ascii"), strict_parsing=True)
                    if parameters.get("grant_type") == ["authorization_code"]:
                        self._metadata()
                        self._token_request_started = self._now()
                response = yield outgoing
                if str(outgoing.url) == OFFICIAL_MCP_ENDPOINT:
                    if response.status_code == 403 and self._record is not None:
                        await self._deny_resource_generation()
                    if self._resource_pending:
                        if response.status_code in {401, 403}:
                            await self._deny_resource_generation()
                        self._require_safe_challenge(response)
                        if not 200 <= response.status_code < 300:
                            raise RuntimeError("official OAuth resource validation uncertain")
                        self._resource_pending = False
                        self._resource_validated = True
                    await self._checkpoint()
                self._require_safe_challenge(response)
                if 300 <= response.status_code < 400:
                    raise RuntimeError("official OAuth redirects disabled")
                try:
                    outgoing = await delegated.asend(response)
                except StopAsyncIteration:
                    failed = False
                    return
        except StopAsyncIteration:
            failed = False
        except Exception:
            raise RuntimeError("official OAuth authentication failed safely") from None
        finally:
            if failed:
                self._poisoned = True
                self.context.clear_tokens()
            await delegated.aclose()
